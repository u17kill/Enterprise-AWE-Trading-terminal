import {afterEach,expect,it,vi} from 'vitest';
import {act,cleanup,fireEvent,render,screen} from '@testing-library/react';
import {PortfolioBooks} from './portfolio-books';
import core from '../../data/portfolio/core.json';
import matrix from '../../data/portfolio/matrix.json';
import type {PortfolioMatrix} from '../lib/portfolio-matrix';
vi.mock('./app-sidebar',()=>({AppSidebar:()=>null}));
vi.mock('./fund-charter-link',()=>({FundCharterLink:()=>null}));
vi.mock('./portfolio-matrix-visuals',()=>({PortfolioMatrixVisuals:()=>null}));
afterEach(()=>{cleanup();localStorage.clear();vi.useRealTimers();vi.unstubAllGlobals();});
const snapshot=(data:typeof core|PortfolioMatrix,revision:string)=>({matrix:data,revision,as_of:'2026-11-24T00:00:00Z',ok:true,error:null});
it('stores an edit immediately and keeps its target book when view changes during the 600ms wait',async()=>{
 vi.useFakeTimers();
 const fetcher=vi.fn(async(url:string,options?:RequestInit)=>{expect(url).toBeTruthy();expect(options?.method).toBe('POST');return new Response(JSON.stringify({ok:true,matrix:core,revision:'core-next',as_of:'2026-11-24T01:00:00Z',backup:'old-core.json'}));});
 vi.stubGlobal('fetch',fetcher);
 render(<PortfolioBooks initialReview={null} initial={{core:snapshot(core,'core-old'),sat:snapshot(matrix as PortfolioMatrix,'sat-old')}} emptyCore={{...core,funds:[]}} emptySat={{...matrix,items:[]} as PortfolioMatrix}/>);
 fireEvent.click(screen.getByRole('button',{name:'核心仓'}));
 fireEvent.click(screen.getByRole('button',{name:new RegExp(core.funds[0].name+' · 编辑')}));
 fireEvent.change(screen.getByLabelText('金额备注（人民币 k）'),{target:{value:'1234k'}});
 fireEvent.click(screen.getByRole('button',{name:'保存'}));
 expect(JSON.parse(localStorage.getItem('pmx_core_v2')!).matrix.funds[0].amount).toBe('1234k');
 expect(fetcher).not.toHaveBeenCalled();
 fireEvent.click(screen.getByRole('button',{name:'卫星仓'}));
 await act(async()=>{await vi.advanceTimersByTimeAsync(599);});expect(fetcher).not.toHaveBeenCalled();
 await act(async()=>{await vi.advanceTimersByTimeAsync(1);});
 expect(fetcher).toHaveBeenCalledTimes(1);expect(fetcher.mock.calls[0][0]).toBe('/api/core');
 const request=fetcher.mock.calls[0][1] as RequestInit;
 expect(JSON.parse(request.body as string).revision).toBe('core-old');
 expect(localStorage.getItem('pmx_map_v1')).toBeNull();
 expect(JSON.parse(localStorage.getItem('pmx_core_v2')!).dirty).toBe(false);
});
